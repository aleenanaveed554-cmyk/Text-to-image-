import streamlit as st
from google import genai
from PIL import Image
import io

# -----------------------------
# Page Configuration
# -----------------------------
st.set_page_config(
    page_title="Gemini Text to Image",
    page_icon="🎨",
    layout="centered"
)

# -----------------------------
# Custom CSS
# -----------------------------
st.markdown("""
<style>
    .main {
        max-width: 900px;
        margin: auto;
    }

    .title {
        text-align: center;
        font-size: 42px;
        font-weight: 800;
        margin-bottom: 5px;
    }

    .subtitle {
        text-align: center;
        color: #777;
        font-size: 17px;
        margin-bottom: 30px;
    }

    .stButton > button {
        width: 100%;
        border-radius: 10px;
        height: 50px;
        font-size: 17px;
        font-weight: 600;
    }
</style>
""", unsafe_allow_html=True)

# -----------------------------
# Header
# -----------------------------
st.markdown(
    '<div class="title">🎨 Gemini Text to Image</div>',
    unsafe_allow_html=True
)

st.markdown(
    '<div class="subtitle">Turn your imagination into an AI-generated image</div>',
    unsafe_allow_html=True
)

# -----------------------------
# API Key
# -----------------------------
try:
    api_key = st.secrets["GEMINI_API_KEY"]
except Exception:
    st.error("❌ GEMINI_API_KEY is not configured in Streamlit Secrets.")
    st.info("Add your Gemini API key to .streamlit/secrets.toml")
    st.stop()

# -----------------------------
# Gemini Client
# -----------------------------
client = genai.Client(api_key=api_key)

# -----------------------------
# Prompt Input
# -----------------------------
prompt = st.text_area(
    "✨ Describe the image you want",
    placeholder="Example: A beautiful futuristic city at sunset, cinematic lighting, ultra detailed",
    height=130
)

# -----------------------------
# Generate Button
# -----------------------------
if st.button("🚀 Generate Image"):

    if not prompt.strip():
        st.warning("Please enter an image description first.")
        st.stop()

    with st.spinner("🎨 Creating your image..."):

        try:
            response = client.models.generate_content(
                model="gemini-3.1-flash-image",
                contents=prompt,
            )

            image_generated = False

            for part in response.parts:

                if part.inline_data is not None:
                    image = part.as_image()

                    st.success("✅ Image generated successfully!")

                    st.image(
                        image,
                        caption="Generated by Gemini",
                        use_container_width=True
                    )

                    # Convert image to bytes for download
                    image_bytes = io.BytesIO()
                    image.save(image_bytes, format="PNG")
                    image_bytes.seek(0)

                    st.download_button(
                        label="⬇️ Download Image",
                        data=image_bytes,
                        file_name="gemini_generated_image.png",
                        mime="image/png"
                    )

                    image_generated = True
                    break

            if not image_generated:
                st.warning(
                    "Gemini did not return an image. Try changing your prompt."
                )

        except Exception as e:
            st.error("❌ Image generation failed.")
            st.code(str(e))
